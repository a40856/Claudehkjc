#!/usr/bin/env python3
"""
regen_predictions.py — Re-score the 11 meetings using today's score_field.

Why: the stored data/predictions/*.xlsx were generated by an earlier version of
predict.py whose feature functions have since drifted. This script bypasses the
network entirely (no Playwright, no HKJC scraping) and just re-runs score_field
on the raw XLSX files we already have cached, writing to data/predictions_regen/.

Output schema matches data/predictions/<tag>.xlsx exactly:
  Predictions sheet  — 22 cols, one row per (race, top-4 pick)
  Summary sheet      — one row per race, P1..P4 side by side
  R1..Rn sheets      — full per-race ranked output

Usage:
    python regen_predictions.py
    python regen_predictions.py --tags 2026-03-25_HV 2026-03-29_ST
    python regen_predictions.py --in data/raw --out data/predictions_regen
"""

import argparse
import json
import os
import sys
from datetime import datetime
from pathlib import Path

import pandas as pd

ROOT          = Path(__file__).resolve().parent.parent
RAW_DIR       = ROOT / "data" / "raw"
PRED_ORIG_DIR = ROOT / "data" / "predictions"
RESULTS_DIR   = ROOT / "data" / "results"
DEFAULT_OUT   = ROOT / "data" / "regen"

# Where the existing stored predictions live — we use this list to pick the
# 11 meetings we want to regen (those that already have ground-truth results
# AND stored predictions, so we can compare apples-to-apples later).
EVAL_MEETINGS = sorted(p.stem for p in PRED_ORIG_DIR.glob("*.xlsx"))


def _ensure_modules_importable():
    sys.path.insert(0, str(ROOT))


def regen_one(tag: str, raw_dir: Path, results_dir: Path, out_path: Path) -> Path | None:
    """Re-score one meeting and write its XLSX. Returns path on success."""
    _ensure_modules_importable()
    from eval_weights import (
        build_stats, build_races, build_history_cache,
    )
    from config import WEIGHTS_GENERAL, WEIGHTS_CLASSIC
    from predict import score_field

    raw_p   = raw_dir   / f"{tag}.xlsx"
    res_p   = results_dir / f"{tag}.xlsx"
    if not (raw_p.exists() and res_p.exists()):
        return None

    jky, trn = build_stats(raw_p)
    races    = build_races(raw_p)
    venue    = tag.split("_")[-1]
    hids = {h["horse_id"] for r in races for h in r["horses"] if h.get("horse_id")}
    hist = build_history_cache(hids)

    # Classic-race detection same as score_field's caller
    classic_names = {"HONG KONG DERBY", "HONG KONG OAKS", "HONG KONG MILE",
                     "HONG KONG CUP", "HONG KONG VASE", "HONG KONG SPRINT",
                     "CHAMPIONS & CHATER CUP", "STANDARD CHARTERED"}

    master_rows, wide_rows, per_race_sheets = [], [], []
    for race in races:
        is_classic = any(k in race.get("race_name", "").upper() for k in classic_names)
        weights = WEIGHTS_CLASSIC if is_classic else WEIGHTS_GENERAL
        scored  = score_field(race, venue, jky, trn, hist, weights)
        if scored.empty:
            continue
        scored = scored.sort_values("win_prob", ascending=False).reset_index(drop=True)

        # Master: top 4
        for pos_i, (_, row) in enumerate(scored.head(4).iterrows(), 1):
            master_rows.append({
                "race_no":   int(race["race_no"]),
                "race_name": race.get("race_name", ""),
                "pos":       pos_i,
                "horse_no":  str(row["horse_no"]),
                "horse":     row["horse_name"],
                "draw":      int(row["draw"]),
                "jockey":    row["jockey"],
                "trainer":   row["trainer"],
                "last6":     row["last6_runs"],
                "s_form":    float(row["s_form"]),
                "s_draw":    float(row["s_draw"]),
                "s_jockey":  float(row["s_jockey"]),
                "s_trainer": float(row["s_trainer"]),
                "s_h2h":     float(row["s_h2h"]),
                "s_rating":  float(row["s_rating"]),
                "s_market":  float(row["s_market"]),
                "composite": round(float(row["composite"]), 4),
                "win_prob%": float(row["win_prob"]),
                "calc_odds": float(row["calc_odds"]),
                "live_odds": "",    # not available at regen time
                "actual_pos": "",   # filled by review.py
                "hit":       "",    # filled by review.py
            })

        # Wide
        wide = {"race_no": int(race["race_no"]), "race_name": race.get("race_name", "")}
        for pos_i, (_, row) in enumerate(scored.head(4).iterrows(), 1):
            wide[f"P{pos_i}_no"]       = str(row["horse_no"])
            wide[f"P{pos_i}_horse"]    = row["horse_name"]
            wide[f"P{pos_i}_draw"]     = int(row["draw"])
            wide[f"P{pos_i}_win%"]     = float(row["win_prob"])
            wide[f"P{pos_i}_calcodds"] = float(row["calc_odds"])
            wide[f"P{pos_i}_jockey"]   = row["jockey"]
        wide_rows.append(wide)

        # Per-race full sheet
        df = scored.copy()
        df.insert(0, "pos", range(1, len(df) + 1))
        per_race_sheets.append((f"R{race['race_no']}", df))

    if not master_rows:
        return None

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with pd.ExcelWriter(out_path, engine="openpyxl") as writer:
        pd.DataFrame(master_rows).to_excel(writer, sheet_name="Predictions", index=False)
        pd.DataFrame(wide_rows).to_excel(writer, sheet_name="Summary", index=False)
        for sheet_name, df in per_race_sheets:
            df.to_excel(writer, sheet_name=sheet_name, index=False)

    return out_path


def main():
    ap = argparse.ArgumentParser(description="Re-score cached raw XLSX with today's score_field.")
    ap.add_argument("--tags", nargs="*", help="Specific meeting tags (default: all with stored preds)")
    ap.add_argument("--all", action="store_true",
                    help="Regen every meeting with raw+results (ignores EVAL_MEETINGS filter)")
    ap.add_argument("--in",   dest="in_dir",  default=str(RAW_DIR),
                    help="Raw XLSX input dir (default: data/raw)")
    ap.add_argument("--out",  dest="out_dir", default=str(DEFAULT_OUT),
                    help="Output dir for regenerated predictions (default: data/regen)")
    args = ap.parse_args()

    raw_dir     = Path(args.in_dir)
    results_dir = RESULTS_DIR
    out_dir     = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.all:
        # Every tag that has both raw + results (apples-to-apples on full history)
        tags = sorted({p.stem for p in raw_dir.glob("*.xlsx")}
                      & {p.stem for p in results_dir.glob("*.xlsx")})
    else:
        tags = args.tags or EVAL_MEETINGS
    print(f"Regenerating {len(tags)} meetings → {out_dir}\n")

    ok = fail = 0
    for tag in tags:
        out_p = out_dir / f"{tag}.xlsx"
        try:
            res = regen_one(tag, raw_dir, results_dir, out_p)
            if res:
                print(f"  ✓ {tag}")
                ok += 1
            else:
                print(f"  ✗ {tag}  (raw or results missing)")
                fail += 1
        except Exception as exc:
            print(f"  ✗ {tag}  ERROR: {exc}")
            fail += 1

    print(f"\nDone: {ok} ok, {fail} failed.")
    print(f"Next: python model_accuracy_report.py "
          f"--pred-dir {out_dir} --out data/model_accuracy_report_regen.json")


if __name__ == "__main__":
    main()
